package com.solerunner.myhealth.data.export

import android.content.Context
import android.graphics.Paint
import android.graphics.Typeface
import android.graphics.pdf.PdfDocument
import com.solerunner.myhealth.domain.model.DoctorSummary
import com.solerunner.myhealth.domain.model.SummaryLine
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.time.format.DateTimeFormatter

/**
 * Offline PDF of the doctor summary. Uses `android.graphics.pdf.PdfDocument`, so there is no renderer
 * dependency and nothing leaves the device until the user shares the file.
 *
 * All body text is wrapped to the printable width; a long medicine name or question no longer runs off
 * the page.
 */
class DoctorSummaryPdf(private val context: Context) {

    suspend fun write(summary: DoctorSummary, patient: String): File = withContext(Dispatchers.IO) {
        val document = PdfDocument()
        val title = Paint().apply { textSize = 20f; typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD) }
        val heading = Paint().apply { textSize = 13f; typeface = Typeface.create(Typeface.DEFAULT, Typeface.BOLD) }
        val body = Paint().apply { textSize = 10.5f }
        val date = DateTimeFormatter.ofPattern("dd MMM yyyy")
        val contentWidth = (PAGE_WIDTH - (MARGIN * 2))

        var pageNumber = 1
        var page = document.startPage(PdfDocument.PageInfo.Builder(PAGE_WIDTH.toInt(), PAGE_HEIGHT.toInt(), pageNumber).create())
        var canvas = page.canvas
        var y = MARGIN + 12f

        fun newPage() {
            document.finishPage(page)
            pageNumber += 1
            page = document.startPage(PdfDocument.PageInfo.Builder(PAGE_WIDTH.toInt(), PAGE_HEIGHT.toInt(), pageNumber).create())
            canvas = page.canvas
            y = MARGIN + 12f
        }

        fun line(text: String, paint: Paint, gap: Float = 15f) {
            if (y > PAGE_HEIGHT - MARGIN) newPage()
            canvas.drawText(text, MARGIN, y, paint)
            y += gap
        }

        fun wrap(text: String, paint: Paint): List<String> {
            if (text.isBlank()) return listOf("")
            val words = text.split(' ')
            val lines = mutableListOf<String>()
            var current = ""
            words.forEach { word ->
                val candidate = if (current.isEmpty()) word else "$current $word"
                if (paint.measureText(candidate) <= contentWidth) {
                    current = candidate
                } else {
                    if (current.isNotEmpty()) lines += current
                    current = word
                }
            }
            if (current.isNotEmpty()) lines += current
            return lines
        }

        fun paragraph(text: String, paint: Paint = body, gap: Float = 15f, indent: String = "") {
            wrap(indent + text, paint).forEach { wrapped -> line(wrapped, paint, gap) }
        }

        line(patient.ifBlank { "My Health" }, title, 26f)
        line("Doctor visit summary", heading, 20f)
        line("Period: " + summary.windowStart.format(date) + " - " + summary.generatedAt.format(date), body, 22f)

        fun section(name: String, lines: List<SummaryLine>) {
            line(name, heading, 20f)
            if (lines.isEmpty()) {
                line("Nothing recorded.", body)
            } else {
                lines.forEach { item ->
                    val value = item.value.takeIf { it.isNotBlank() }?.let { " ($it)" }.orEmpty()
                    paragraph("- " + item.label + value)
                    item.detail?.let { paragraph(it, body, 14f, indent = "    ") }
                }
            }
            y += 8f
        }

        section("What changed", summary.headline)
        section("Needs discussion", summary.flagged)
        section("Improved / information", summary.improved)
        line("Current medicines", heading, 20f)
        if (summary.medicines.isEmpty()) line("None recorded.", body) else summary.medicines.forEach { paragraph("- $it") }
        y += 12f
        line("Treatments", heading, 20f)
        if (summary.treatments.isEmpty()) line("None recorded.", body) else summary.treatments.forEach { paragraph("- $it") }
        y += 12f
        section("Device averages", summary.deviceAverages)
        section("Questions to ask", summary.questions)
        paragraph("Generated by My Health on this phone. Not a medical device.", body, 14f)

        document.finishPage(page)
        val directory = File(context.cacheDir, "exports").apply { mkdirs() }
        val file = File(directory, "doctor-summary-" + summary.generatedAt + ".pdf")
        file.outputStream().use { document.writeTo(it) }
        document.close()
        file
    }

    private companion object {
        const val PAGE_WIDTH = 595f
        const val PAGE_HEIGHT = 842f
        const val MARGIN = 44f
    }
}
